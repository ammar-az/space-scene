import { z } from "zod";

export const SCHEMA_VERSION = 1;
export const GENERATOR_VERSION = "1";
const number = (min: number, max: number) => z.number().min(min).max(max);
const color = z
  .string()
  .regex(/^#[0-9a-fA-F]{6}$/, "Use a six-digit hex color");
const seed = number(0, 2 ** 32 - 1).int();
const name = z.string().trim().min(1).max(80);
const vector = z.tuple([
  number(-2000, 2000),
  number(-2000, 2000),
  number(-2000, 2000),
]);
const range = (min: number, max: number, integer = false) =>
  z
    .tuple([
      integer ? number(min, max).int() : number(min, max),
      integer ? number(min, max).int() : number(min, max),
    ])
    .refine(([low, high]) => low <= high, "Minimum must not exceed maximum");
// Text seeds preserve artwork originally generated by the portfolio.
const planetSeed = z.union([seed, z.string().min(1).max(100)]);
const family = z.strictObject({
  color,
  accent: color,
  detail: number(0, 2),
  intense: z.boolean().optional(),
});

export const planetSchema = z.strictObject({
  id: z.string().regex(/^[a-zA-Z0-9_-]{1,100}$/),
  name,
  visible: z.boolean(),
  type: z.enum(["rocky", "gas", "icy"]),
  locked: z.boolean(),
  radius: number(1, 14),
  moonCount: number(0, 12).int(),
  ringCount: number(0, 4).int(),
  seeds: z.strictObject({
    surface: planetSeed,
    moons: planetSeed,
    rings: planetSeed,
    weather: planetSeed,
  }),
  families: z.strictObject({ rocky: family, gas: family, icy: family }),
  ranges: z.strictObject({
    radius: range(1, 14),
    moons: range(0, 12, true),
    rings: range(0, 4, true),
    detail: range(0, 2),
  }),
  orbit: z.strictObject({
    radius: number(30, 240),
    eccentricity: number(0, 0.65),
    inclination: number(-80, 80),
    orientation: number(-180, 180),
    phase: number(0, 360),
    speed: number(-20, 20),
    center: vector,
  }),
  spin: z.strictObject({
    tilt: number(-180, 180),
    orientation: number(-180, 180),
    phase: number(0, 360),
    speed: number(-60, 60),
  }),
});

export const backgroundSchema = z.strictObject({
  visible: z.boolean(),
  seed,
  density: number(0.1, 3),
  size: number(0.3, 2.5),
  brightness: number(0.1, 2),
  twinkle: z.boolean(),
  clusterFrequency: number(0, 5).optional(),
  largeStarFrequency: number(0, 5).optional(),
  deepSky: z
    .strictObject({
      visible: z.boolean(),
      seed,
      density: number(0, 1.5),
      size: number(0.3, 3),
      brightness: number(0.1, 3),
    })
    .optional(),
});
export const sceneSchema = z
  .strictObject({
    name,
    timeline: z.strictObject({
      elapsed: number(0, 1e12),
      solar: number(0, 1e12),
    }),
    background: backgroundSchema,
    sun: z.strictObject({
      visible: z.boolean(),
      seed,
      radius: number(5, 80),
      color,
      highlight: color,
      shadow: color,
      activity: z.boolean(),
      position: vector,
    }),
    planets: z.array(planetSchema).max(64),
    view: z.strictObject({
      preset: z.enum(["overhead", "centered", "offset"]),
      framing: z.enum(["standard", "portfolio"]).optional(),
      zoom: number(0.35, 4),
      pan: vector,
    }),
    motion: z.strictObject({
      playing: z.boolean(),
      speed: number(0, 5),
      orbitLines: z.boolean(),
      orbitEpoch: number(0, 1e12),
    }),
  })
  .refine(
    (scene) =>
      new Set(scene.planets.map((planet) => planet.id)).size ===
      scene.planets.length,
    "Planet IDs must be unique",
  );

const version = {
  schemaVersion: z.literal(SCHEMA_VERSION),
  generatorVersion: z.literal(GENERATOR_VERSION),
};
export const presetSchema = z.discriminatedUnion("kind", [
  z.strictObject({
    kind: z.literal("space-scene"),
    ...version,
    scene: sceneSchema,
  }),
  z.strictObject({
    kind: z.literal("space-planet"),
    ...version,
    planet: planetSchema,
  }),
]);
export type Planet = z.infer<typeof planetSchema>;
export type SceneModel = z.infer<typeof sceneSchema>;
export type Background = z.infer<typeof backgroundSchema>;
export type Preset = z.infer<typeof presetSchema>;
export type ViewPreset = SceneModel["view"]["preset"];

export function serializeScene(scene: SceneModel): string {
  return JSON.stringify(
    presetSchema.parse({
      kind: "space-scene",
      schemaVersion: SCHEMA_VERSION,
      generatorVersion: GENERATOR_VERSION,
      scene,
    }),
    null,
    2,
  );
}
export function serializePlanet(planet: Planet): string {
  return JSON.stringify(
    presetSchema.parse({
      kind: "space-planet",
      schemaVersion: SCHEMA_VERSION,
      generatorVersion: GENERATOR_VERSION,
      planet,
    }),
    null,
    2,
  );
}
export function parsePreset(source: string): Preset {
  if (source.length > 2_000_000)
    throw new Error("Preset must be smaller than 2 MB.");
  let value: unknown;
  try {
    value = JSON.parse(source);
  } catch {
    throw new Error("This file is not valid JSON.");
  }
  const result = presetSchema.safeParse(value);
  if (!result.success) {
    const issue = result.error.issues[0];
    throw new Error(
      `Invalid preset at ${issue.path.join(".") || "root"}: ${issue.message}. Supported schema: ${SCHEMA_VERSION}, generator: ${GENERATOR_VERSION}.`,
    );
  }
  return result.data;
}
