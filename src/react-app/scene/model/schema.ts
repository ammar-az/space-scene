import { roundDiameter } from "./sizes.ts";
import { z } from "zod";

export const SCHEMA_VERSION = 4;
export const GENERATOR_VERSION = "4";
const number = (min: number, max: number) => z.number().min(min).max(max);
const color = z
  .string()
  .regex(/^#[0-9a-fA-F]{6}$/, "Use a six-digit hex color");
const seed = number(0, 2 ** 32 - 1).int();
const name = z.string().trim().min(1).max(80);
const vector = z.tuple([
  number(-2000, 2000),
  number(-2000, 2000),
  number(-2000, 2000),
]);
const physicalVector = z.tuple([
  number(-1000000, 1000000),
  number(-1000000, 1000000),
  number(-1000000, 1000000),
]);
const range = (min: number, max: number, integer = false) =>
  z
    .tuple([
      integer ? number(min, max).int() : number(min, max),
      integer ? number(min, max).int() : number(min, max),
    ])
    .refine(([low, high]) => low <= high, "Minimum must not exceed maximum");
// Text seeds preserve artwork originally generated by the portfolio.
const planetSeed = z.union([seed, z.string().min(1).max(100)]);
const family = z.strictObject({
  color,
  accent: color,
  detail: number(0, 2),
  intense: z.boolean().optional(),
  bandShadow: color.optional(),
  palette: z
    .array(z.strictObject({ color, accent: color }))
    .min(1)
    .max(16)
    .optional(),
});

export const notableMoonSchema = z
  .strictObject({
    id: z.string().regex(/^[a-zA-Z0-9_-]{1,100}$/),
    name,
    visible: z.boolean(),
    locked: z.boolean(),
    diameter: number(0.000001, 1000000), // thousands of km; retain sub-km precision for small named moons.
    seed: planetSeed,
    surface: z.strictObject({ color, accent: color, detail: number(0, 2) }),
    orbit: z.strictObject({
      radiusX: number(0.000001, 1e9),
      radiusZ: number(0.000001, 1e9), // thousands of km
      rotation: number(-180, 180),
      inclination: number(-180, 180),
      orientation: number(-180, 180),
      phase: number(0, 360),
      periodDays: number(0.000001, 1e9),
      reverse: z.boolean(),
      playing: z.boolean(),
    }),
    spin: z.strictObject({
      tidallyLocked: z.boolean(),
      periodHours: number(0.000001, 1e12),
      tilt: number(-180, 180),
      orientation: number(-180, 180),
      phase: number(0, 360),
      reverse: z.boolean(),
      playing: z.boolean(),
    }),
  })
  .transform((moon) =>
    moon.spin.tidallyLocked
      ? {
          ...moon,
          spin: { ...moon.spin, periodHours: moon.orbit.periodDays * 24 },
        }
      : moon,
  );
export type NotableMoon = z.infer<typeof notableMoonSchema>;

export const planetSchema = z.strictObject({
  id: z.string().regex(/^[a-zA-Z0-9_-]{1,100}$/),
  name,
  visible: z.boolean(),
  type: z.enum(["rocky", "gas", "icy"]),
  locked: z.boolean(),
  earthlike: z
    .strictObject({
      enabled: z.boolean(),
      oceanColor: color,
      landColor: color,
      desertColor: color,
      landCoverage: number(0.05, 0.85),
      continentScale: number(1, 5),
    })
    .optional(),
  diameter: number(0.01, 1000000).transform(roundDiameter),
  moonCount: number(0, 64).int(),
  proceduralMoons: z.boolean(),
  notableMoons: z
    .array(notableMoonSchema)
    .max(64)
    .refine(
      (moons) => new Set(moons.map((m) => m.id)).size === moons.length,
      "Moon IDs must be unique within each planet",
    ),
  moonSystem: z.strictObject({
    distanceCompression: number(0, 1),
    orbitScale: number(0.5, 5),
    sizeCompression: number(0, 1),
    sizeScale: number(0.25, 5),
  }),
  atmosphere: z
    .strictObject({
      visible: z.boolean(),
      color,
      density: number(0, 1),
      height: number(0.005, 0.2),
    })
    .optional(),
  clouds: z
    .strictObject({
      visible: z.boolean(),
      color,
      coverage: number(0, 1),
      opacity: number(0, 1),
      scale: number(1, 12),
      altitude: number(0.005, 0.08),
      speed: number(-10, 10),
      evolution: number(0, 2).optional(),
    })
    .optional(),
  ringCount: number(0, 4).int(), // Legacy belts; explicit rings take precedence.
  rings: z
    .strictObject({
      amount: number(0, 1),
      width: number(0.05, 1),
      opacity: number(0, 1),
      innerRadius: number(1.05, 2.5),
    })
    .optional(),
  moons: z
    .strictObject({
      colors: z.array(color).min(1).max(8),
      radius: range(1.2, 12),
      speed: range(-60, 60),
      size: range(0.03, 0.4),
      inclination: range(-80, 80),
    })
    .optional(),
  seeds: z.strictObject({
    surface: planetSeed,
    moons: planetSeed,
    rings: planetSeed,
    weather: planetSeed,
    clouds: planetSeed.optional(),
  }),
  families: z.strictObject({ rocky: family, gas: family, icy: family }),
  ranges: z.strictObject({
    diameter: range(0.01, 1000000).transform(
      ([low, high]) =>
        [roundDiameter(low), roundDiameter(high)] as [number, number],
    ),
    moons: range(0, 64, true),
    rings: range(0, 4, true),
    ringAmount: range(0, 1).optional(),
    ringProbability: number(0, 1).optional(),
    detail: range(0, 2),
  }),
  orbit: z.strictObject({
    inclination: number(-80, 80),
    orientation: number(-180, 180),
    phase: number(0, 360),
    periodDays: number(0.000001, 1e12),
    reverse: z.boolean(),
    playing: z.boolean(),
    center: physicalVector,
    ellipse: z.strictObject({
      radiusX: number(0.000001, 1e9),
      radiusZ: number(0.000001, 1e9),
      rotation: number(-180, 180),
      anchor: z.enum(["center", "sun"]),
    }),
  }),
  spin: z.strictObject({
    tilt: number(-180, 180),
    orientation: number(-180, 180),
    phase: number(0, 360),
    periodHours: number(0.000001, 1e12),
    reverse: z.boolean(),
    playing: z.boolean(),
  }),
});

export const backgroundSchema = z.strictObject({
  visible: z.boolean(),
  seed,
  density: number(0.1, 3),
  size: number(0.3, 2.5),
  brightness: number(0.1, 2),
  twinkle: z.boolean(),
  clusterFrequency: number(0, 5).optional(),
  largeStarFrequency: number(0, 5).optional(),
  deepSky: z
    .strictObject({
      visible: z.boolean(),
      seed,
      density: number(0, 1.5),
      size: number(0.3, 3),
      brightness: number(0.1, 3),
    })
    .optional(),
});
export const sceneSchema = z
  .strictObject({
    name,
    timeline: z.strictObject({
      elapsed: number(0, 1e12),
      solar: number(0, 1e12),
      rotationHours: number(0, 1e18),
      orbitDays: number(0, 1e18),
      moonDays: number(0, 1e18),
    }),
    background: backgroundSchema,
    sun: z.strictObject({
      visible: z.boolean(),
      seed,
      diameter: number(0.01, 1000000000).transform(roundDiameter),
      color,
      highlight: color,
      shadow: color,
      activity: z.boolean(),
      position: physicalVector,
    }),
    planets: z.array(planetSchema).max(64),
    sizing: z.strictObject({
      planetCompression: number(0, 1),
      planetScale: number(1, 5).transform(roundDiameter),
      starScale: number(0.1, 1).transform(roundDiameter),
    }),
    layout: z
      .strictObject({
        distanceCompression: number(0, 1),
        orbitScale: number(0.5, 5),
        orbitSpacing: number(0.5, 5),
      })
      .optional(),
    view: z.strictObject({
      preset: z.enum(["overhead", "centered", "offset"]),
      framing: z.enum(["standard", "portfolio"]).optional(),
      camera: z
        .strictObject({
          azimuth: number(-180, 180),
          elevation: number(-90, 90),
          target: z.tuple([
            number(-1000000, 1000000),
            number(-1000000, 1000000),
            number(-1000000, 1000000),
          ]),
          baseHeight: number(1, 1000000),
          followPlanetId: z
            .string()
            .regex(/^[a-zA-Z0-9_-]{1,100}$/)
            .optional(),
        })
        .optional(),
      zoom: number(0.01, 1000000),
      pan: vector,
    }),
    motion: z.strictObject({
      playing: z.boolean(),
      speed: number(0, 5),
      orbitLines: z.boolean(),
      orbitEpochDays: number(0, 1e18),
      moonEpochDays: number(0, 1e18),
      rotationRate: z.strictObject({
        unit: z.enum(["hour/hour", "hour/minute", "hour/second"]),
        multiplier: number(0.1, 10),
      }),
      orbitRate: z.strictObject({
        unit: z.enum(["day/minute", "day/second"]),
        multiplier: number(1, 100).int(),
      }),
      moonRate: z.strictObject({
        unit: z.enum(["day/minute", "day/second"]),
        multiplier: number(1, 100).int(),
      }),
    }),
  })
  .refine(
    (scene) =>
      new Set(scene.planets.map((planet) => planet.id)).size ===
      scene.planets.length,
    "Planet IDs must be unique",
  )
  .refine(
    (scene) =>
      !scene.view.camera?.followPlanetId ||
      scene.planets.some(
        (planet) =>
          planet.id === scene.view.camera?.followPlanetId && planet.visible,
      ),
    "The followed planet must be visible and belong to this scene",
  );

const version = {
  schemaVersion: z.literal(SCHEMA_VERSION),
  generatorVersion: z.literal(GENERATOR_VERSION),
};
export const presetSchema = z.discriminatedUnion("kind", [
  z.strictObject({
    kind: z.literal("space-scene"),
    ...version,
    scene: sceneSchema,
  }),
  z.strictObject({
    kind: z.literal("space-planet"),
    ...version,
    planet: planetSchema,
  }),
]);
export type Planet = z.infer<typeof planetSchema>;
export type SceneModel = z.infer<typeof sceneSchema>;
export type Background = z.infer<typeof backgroundSchema>;
export type Preset = z.infer<typeof presetSchema>;
export type ViewPreset = SceneModel["view"]["preset"];

export function serializeScene(scene: SceneModel): string {
  return JSON.stringify(
    presetSchema.parse({
      kind: "space-scene",
      schemaVersion: SCHEMA_VERSION,
      generatorVersion: GENERATOR_VERSION,
      scene,
    }),
    null,
    2,
  );
}
export function serializePlanet(planet: Planet): string {
  return JSON.stringify(
    presetSchema.parse({
      kind: "space-planet",
      schemaVersion: SCHEMA_VERSION,
      generatorVersion: GENERATOR_VERSION,
      planet,
    }),
    null,
    2,
  );
}
export function parsePreset(source: string): Preset {
  if (source.length > 2_000_000)
    throw new Error("Preset must be smaller than 2 MB.");
  let value: unknown;
  try {
    value = JSON.parse(source);
  } catch {
    throw new Error("This file is not valid JSON.");
  }
  const result = presetSchema.safeParse(value);
  if (!result.success) {
    const issue = result.error.issues[0];
    throw new Error(
      `Invalid preset at ${issue.path.join(".") || "root"}: ${issue.message}. Supported schema: ${SCHEMA_VERSION}, generator: ${GENERATOR_VERSION}.`,
    );
  }
  return result.data;
}
